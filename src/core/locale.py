def get_locale() -> str:
    """取得目前語言代碼"""
    return _current_locale


def is_english() -> bool:
    """目前介面語言是否為英文"""
    return _current_locale == LOCALE_EN


def localized(zh: _T, en: _T) -> _T:
    """依目前介面語言挑選中文或英文版本

    Args:
        zh: 中文版本
        en: 英文版本

    Returns:
        介面語言為英文時為 en，否則為 zh
    """
    return en if is_english() else zh


def trash_name(os_name: str = os.name) -> str:
    """系統回收處在目前介面語言的稱呼：Windows 是資源回收桶，其他平台（Linux）是垃圾桶

    Args:
        os_name: 平台的 os.name，預設為目前的平台

    Returns:
        句中用的稱呼，例如「垃圾桶」、"recycle bin"
    """
    windows, others = _TRASH_NAMES.get(_current_locale, _TRASH_NAMES[LOCALE_ZH_TW])
    return windows if os_name == "nt" else others


def set_locale(locale_code: str):
    """設定目前語言

    Args:
        locale_code: 語言代碼，"zh_TW" 或 "en"
    """
    global _current_locale
    if locale_code in _STRINGS:
        _current_locale = locale_code


def get_available_locales():
    """取得所有可用語言代碼"""
    return list(_STRINGS.keys())


def language_names() -> List[Tuple[str, str]]:
    """可選的介面語言，依顯示順序列出（語言代碼，名稱）；語言選單與譜庫的欄位語言選單共用"""
    return [(code, t(key)) for code, key in _LANGUAGE_NAME_KEYS.items()]


def get_keys(locale_code: str) -> FrozenSet[str]:
    """取得某語言字典的所有字串鍵

    Args:
        locale_code: 語言代碼，"zh_TW" 或 "en"

    Returns:
        該語言的字串鍵集合
    """
    return frozenset(_STRINGS[locale_code])


def t(key: str, **kwargs) -> str:
    """取得翻譯字串

    字串裡的 {trash}、{Trash} 換成這個平台的系統回收處稱呼（後者首字母大寫），不必由呼叫端傳入。

    Args:
        key: 點分階層鍵名，例如 "menu.file.new"
        **kwargs: 用於 str.format_map() 的參數

    Returns:
        翻譯後的字串，找不到時回傳鍵名本身
    """
    strings = _STRINGS.get(_current_locale, _STRINGS[LOCALE_ZH_TW])
    text = strings.get(key)
    if text is None:
        fallback = _STRINGS[LOCALE_ZH_TW]
        text = fallback.get(key, key)
    trash = trash_name()
    text = text.replace("{trash}", trash).replace("{Trash}", trash.title())
    if kwargs:
        try:
            text = text.format_map(kwargs)
        except (KeyError, ValueError):
            pass
    return text
